fn write_files(home: &Home, config: &str, models: &str) {
    std::fs::create_dir_all(home.dir().join("prompt")).unwrap();
    std::fs::write(home.config_file(), config).unwrap();
    std::fs::write(home.models_file(), models).unwrap();
    std::fs::write(home.system_prompt_file(), "You are a coding agent.\n").unwrap();
    std::fs::write(home.dir().join("prompt/review.md"), "Review only.\n").unwrap();
}

fn temp_home(config: &str, models: &str) -> (tempfile::TempDir, Home) {
    let dir = tempfile::tempdir().unwrap();
    let home = Home(dir.path().to_path_buf());
    write_files(&home, config, models);
    (dir, home)
}

/// The rejection's text, with the temporary directory shown as `<home>` and
/// `/` as the separator on every platform.
fn failure(config: &str, models: &str) -> String {
    let (dir, home) = temp_home(config, models);
    let error = load(&home)
        .err()
        .expect("the configuration should be rejected");
    shown(&error.to_string(), &dir)
}

fn shown(message: &str, dir: &tempfile::TempDir) -> String {
    message
        .replace(dir.path().to_str().unwrap(), "<home>")
        .replace(std::path::MAIN_SEPARATOR, "/")
}

/// The 1-based line of the first line of `text` that contains `needle`.
fn line_of(text: &str, needle: &str) -> usize {
    text.lines().position(|line| line.contains(needle)).unwrap() + 1
}

