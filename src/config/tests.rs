#[test]
fn the_system_prompt_must_exist_and_have_text() {
    let (dir, home) = temp_home(CONFIG, MODELS);
    let rejection = |home: &Home| shown(&load(home).err().unwrap().to_string(), &dir);
    std::fs::write(home.system_prompt_file(), " \n\n").unwrap();
    assert_eq!(
        rejection(&home),
        "<home>/prompt/SYSTEM_PROMPT.md: system prompt is empty"
    );
    std::fs::remove_file(home.system_prompt_file()).unwrap();
    assert!(rejection(&home).contains("system prompt not found"));

    std::fs::write(home.system_prompt_file(), "ok").unwrap();
    std::fs::remove_file(home.dir().join("prompt/review.md")).unwrap();
    let message = rejection(&home);
    assert!(
        message.starts_with(&format!(
            "<home>/config.toml:{}: [profiles.review] prompt: ",
            line_of(CONFIG, "prompt/review.md")
        )),
        "{message}"
    );
}

#[test]
fn startup_writes_a_private_agent_config_every_time() {
    let (_dir, home) = temp_home(CONFIG, MODELS);
    let request = Request::default();
    let Prepared::Launch(launch) = prepare(&home, &request, &|_| true).unwrap() else {
        panic!("a configured directory launches");
    };
    assert_eq!(launch.agent_config, home.agent_config_file());
    assert!(launch.composed);
    std::fs::write(&launch.agent_config, "stale").unwrap();
    prepare(&home, &request, &|_| true).unwrap();
    let text = std::fs::read_to_string(&launch.agent_config).unwrap();
    assert!(text.starts_with("# Generated by minicore-tui"), "{text}");
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mode = std::fs::metadata(&launch.agent_config)
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o600);
    }
}

#[test]
fn the_launch_is_refused_for_a_missing_key_or_an_unknown_profile_or_model() {
    let (_dir, home) = temp_home(CONFIG, MODELS);
    let refused = |request: Request, has: bool| match prepare(&home, &request, &|_| has) {
        Err(message) => message,
        Ok(_) => panic!("expected a refusal"),
    };
    assert!(
        refused(Request::default(), false)
            .starts_with("environment variable LUNA_API_KEY is not set")
    );
    let request = Request {
        profile: Some("fast"),
        ..Request::default()
    };
    assert!(refused(request, true).starts_with("--profile \"fast\" is not defined in config.toml"));
    let request = Request {
        model: Some("other"),
        ..Request::default()
    };
    assert!(refused(request, true).starts_with("--model \"other\" is not defined in models.toml"));
}

#[test]
fn a_raw_agent_config_skips_composition_and_first_run() {
    let dir = tempfile::tempdir().unwrap();
    let home = Home(dir.path().to_path_buf());
    let raw = Path::new("/etc/agent.toml");
    let request = Request {
        agent_config: Some(raw),
        ..Request::default()
    };
    let Prepared::Launch(launch) = prepare(&home, &request, &|_| false).unwrap() else {
        panic!("a raw config launches");
    };
    assert_eq!(launch.agent_config, raw);
    assert!(!launch.composed);
    assert!(!home.config_file().exists() && !home.session_dir().exists());
    assert_eq!(launch.agent_binary, None);
}

#[test]
fn the_agent_binary_is_the_flag_then_the_setting_then_the_built_in_one() {
    let dir = tempfile::tempdir().unwrap();
    let home = Home(dir.path().to_path_buf());
    // A leftover bundled agent from an older package is not picked up.
    std::fs::create_dir(dir.path().join("bin")).unwrap();
    std::fs::write(dir.path().join("bin/minicore-agent"), "").unwrap();
    assert_eq!(agent_binary(&home, None, None), None);
    assert_eq!(
        agent_binary(&home, None, Some("other/agent".into())),
        Some(dir.path().join("other/agent"))
    );
    assert_eq!(
        agent_binary(
            &home,
            Some(Path::new("/x/agent")),
            Some("other/agent".into())
        ),
        Some(PathBuf::from("/x/agent"))
    );
}

