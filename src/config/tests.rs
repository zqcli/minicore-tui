#[test]
fn saving_the_theme_keeps_comments_and_other_settings() {
    let dir = tempfile::tempdir().unwrap();
    let file = dir.path().join("config.toml");
    std::fs::write(
        &file,
        "# mine\ndefault_profile = \"x\"\n\n[ui]\nbell = false # quiet\n",
    )
    .unwrap();
    save_theme(&file, ThemeKind::Light).unwrap();
    let text = std::fs::read_to_string(&file).unwrap();
    assert!(
        text.contains("# mine") && text.contains("bell = false # quiet"),
        "{text}"
    );
    assert!(text.contains("theme = \"light\""), "{text}");
    std::fs::write(&file, "default_profile = \"x\"\n").unwrap();
    save_theme(&file, ThemeKind::Dark).unwrap();
    let settings = std::fs::read_to_string(&file).unwrap();
    assert!(
        settings.contains("[ui]") && settings.contains("theme = \"dark\""),
        "{settings}"
    );
}

